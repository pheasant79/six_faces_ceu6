/**
  ******************************************************************************
  * @file    led.c
  * @brief   LED控制模块源文件
  * @details 控制PA7引脚作为开漏输出实现LED控制
  *          开漏输出特性：高阻态无电流，LED不亮；
  *                      低电平有电流，LED亮起
  ******************************************************************************
  */

/* 包含头文件 ------------------------------------------------------------------*/
#include "led.h"

/*-----------------------------------------------------------------------------*/
/* 私有类型定义 ----------------------------------------------------------------*/

/* 私有宏定义 ------------------------------------------------------------------*/

/* 私有变量 --------------------------------------------------------------------*/
static uint8_t g_led_state = 0; // 记录LED状态：0关闭，1打开

/* 私有函数原型 ----------------------------------------------------------------*/

/*-----------------------------------------------------------------------------*/
/* 函数实现 --------------------------------------------------------------------*/

/**
  * @brief  初始化LED控制
  * @note   PA7已在gpio.c中配置为开漏输出模式，这里只需确保初始状态
  * @retval 无
  */
void LED_Init(void)
{
  /* LED引脚已在MX_GPIO_Init中配置为开漏输出
   * 初始电平为高（GPIO_PIN_SET），此时无电流，LED不亮
   */
  
  /* 确保初始状态为关闭LED */
  LED_OFF();
  g_led_state = 0;
}

/**
  * @brief  打开LED灯
  * @note   设置PA7为低电平，形成电流通路，LED亮起
  * @retval 无
  */
void LED_TurnOn(void)
{
  LED_ON();
  g_led_state = 1;
}

/**
  * @brief  关闭LED灯
  * @note   设置PA7为高阻态，无电流，LED不亮
  * @retval 无
  */
void LED_TurnOff(void)
{
  LED_OFF();
  g_led_state = 0;
}

/**
  * @brief  切换LED灯状态
  * @note   根据当前状态切换LED开关
  * @retval 无
  */
void LED_Toggle(void)
{
  if (g_led_state)
  {
    LED_TurnOff();
  }
  else
  {
    LED_TurnOn();
  }
}

/**
  * @brief  获取LED灯当前状态
  * @note   返回LED灯的开关状态
  * @retval 0: 关闭, 1: 打开
  */
uint8_t LED_GetState(void)
{
  return g_led_state;
}

